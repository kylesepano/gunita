function nearbyAlternatives(event: ImportedEvent) {
  const byYear = (left: ImportedEvent, right: ImportedEvent) =>
    Math.abs(left.year - event.year) - Math.abs(right.year - event.year)
  const candidates = imported.filter((candidate) => candidate.id !== event.id).sort(byYear)
  return [
    ...candidates.filter((candidate) => candidate.country === event.country),
    ...candidates.filter((candidate) => candidate.country !== event.country),
  ]
    .slice(0, 2)
    .map((candidate) => `Conditions surrounding ${candidate.title}`)
}

